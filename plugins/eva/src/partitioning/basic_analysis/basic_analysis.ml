open Eva_automata

module MemLoc = Basic_locations
module VtLocMap = MemLoc.Map (Vertex)

module LastWrites =
struct
  type t = VtLocMap.t

  let initial = VtLocMap.empty

  let join v lw1 lw2 =
    let merge _ v1 v2 =
      match v1, v2 with
      | Some v1, Some v2 when v1 == v2 -> v1
      | _ -> v
    in
    VtLocMap.generic_join ~cache:NoCache ~symmetric:true ~idempotent:true
      ~decide:merge lw1 lw2

  let widen _ _ = Fixpoint

  let transfer (_, _, v) lw locs =
    MemLoc.Set.fold (fun ml -> VtLocMap.add ml v) locs lw
end

module PtrTargets =
struct
  type t = MemLoc.SetMap.t

  let initial formals =
    let add_arg_pt pt = function
      | { Cil_types.vtype = { tnode = TPtr _ } } as vi ->
        let target = MemLoc.Set.singleton MemLoc.InputMem in
        MemLoc.SetMap.add (MemLoc.Var vi) target pt
      | _ -> pt
    in
    List.fold_left add_arg_pt MemLoc.SetMap.empty formals

  let join _ pt1 pt2 =
    MemLoc.SetMap.join ~cache:NoCache ~symmetric:true ~idempotent:true
      ~decide:(fun _ -> MemLoc.Set.union) pt1 pt2

  let widen pt1 pt2 =
    let included =
      MemLoc.SetMap.binary_predicate NoCache UniversalPredicate
        ~decide_fast:(fun _ _ -> PUnknown)
        ~decide_fst:(fun _ _ -> false)
        ~decide_snd:(fun _ _ -> true)
        ~decide_both:(fun _ -> MemLoc.Set.subset)
        pt2 pt1
    in
    if included then Fixpoint
    else Widening pt2

  (* Update pt (the map of pointer targets) for the assignment of target_locs
     to ml. The update may be weak and a new heap block may be generated by
     an allocation statement (i.e. a call). *)
  let do_assignment ?alloc_stmt weak_update target_locs ml pt =
    let target_locs =
      match ml with
      | MemLoc.Var _ when not weak_update -> target_locs
      | _ ->
        (* The only non-weak update is when we know we are assigning to a
           simple variable *)
        try MemLoc.SetMap.find ml pt |> MemLoc.Set.union target_locs
        with Not_found -> target_locs
    in
    let target_locs =
      match alloc_stmt with
      | None -> target_locs
      | Some stmt -> MemLoc.Set.add (MemLoc.HeapBlk stmt) target_locs
    in
    MemLoc.SetMap.add ml target_locs pt

  let do_argument stmt = do_assignment ~alloc_stmt:stmt true

  (* - assigned_locs: the locations that are assigned to
     - target_locs: the locations that are assigned
     - args_locs: the arguments passed by address (recursively)
     - ptr_args_locs: the pointer-typed arguments passed by address
       (recursively) *)
  let transfer (_, e, _) pt
      (assigned_locs, target_locs, args_locs, ptr_args_locs) =
    let lval_is_compound (lval : Eva_ast.lval) =
      match snd lval.node with NoOffset -> false | _ -> true
    in
    let is_weak_assign lval =
      lval_is_compound lval || MemLoc.Set.cardinal assigned_locs > 1
    in

    match e.edge_transition with
    | Assign (lval, _, _) ->
      let weak_update = is_weak_assign lval in
      MemLoc.Set.fold (do_assignment weak_update target_locs) assigned_locs pt
    | Init (vi, _, _) ->
      if MemLoc.Set.is_empty target_locs then pt
      else MemLoc.SetMap.add (MemLoc.Var vi) target_locs pt
    | Call (Some lval, _, _, stmt) ->
      let weak_update = is_weak_assign lval in
      MemLoc.Set.fold
        (do_assignment ~alloc_stmt:stmt weak_update args_locs)
        assigned_locs pt
      |> MemLoc.Set.fold (do_argument stmt args_locs) ptr_args_locs
    | Call (None, _, _, stmt) ->
      MemLoc.Set.fold (do_argument stmt args_locs) ptr_args_locs pt
    | _ -> pt
end

type lw_and_pt = LastWrites.t * PtrTargets.t

module LwAndPt (Info : sig val include_guards : bool end) =
struct
  type t = lw_and_pt

  let initial formals = LastWrites.initial, PtrTargets.initial formals

  let join v (lw1, pt1) (lw2, pt2) =
    LastWrites.join v lw1 lw2, PtrTargets.join v pt1 pt2

  let widen (lw1, pt1) (lw2, pt2) =
    match LastWrites.widen lw1 lw2, PtrTargets.widen pt1 pt2 with
    | Fixpoint, Fixpoint -> Fixpoint
    | Widening st_d1, Fixpoint -> Widening (st_d1, pt2)
    | Fixpoint, Widening st_d2 -> Widening (lw2, st_d2)
    | Widening st_d1, Widening st_d2 -> Widening (st_d1, st_d2)

  let compute_locs e pt =
    let open MemLoc.Util (struct let ptr_targets = pt end) in

    let add_arg_locs (target_locs, ptr_locs) (arg : Eva_ast.exp) =
      match arg.typ.tnode with
      | TPtr typ ->
        let locs = locs_of_exp arg |> recursive_locs in
        let ptr_locs =
          if typ_is_ptr typ then MemLoc.Set.union ptr_locs locs
          else ptr_locs
        in
        MemLoc.Set.union target_locs locs, ptr_locs
      | _ -> target_locs, ptr_locs
    in
    let rec guarded_locs (exp : Eva_ast.exp) =
      match exp.node with
      | CastE (_, exp) | UnOp (_, exp, _) -> guarded_locs exp
      | BinOp (_, exp1, exp2, _) ->
        MemLoc.Set.union (guarded_locs exp1) (guarded_locs exp2)
      | Lval lval -> locs_of_lval lval
      | _ -> MemLoc.Set.empty
    in

    let nolocs = MemLoc.Set.empty in
    match e.edge_transition with
    | Assign (lval, exp, _) ->
      let target_locs =
        if typ_is_ptr lval.typ then locs_of_exp exp else nolocs
      in
      locs_of_lval lval, target_locs, nolocs, nolocs
    | Init (vi, init, _) ->
      let assigned_locs = MemLoc.Set.singleton (MemLoc.Var vi) in
      assigned_locs, locs_of_init init, nolocs, nolocs
    | Call (lval, lhost, args, _) when not (Eva_ast.is_no_effect_frama_c_builtin lhost) ->
      let assigned_locs =
        match lval with Some lval -> locs_of_lval lval | None -> nolocs
      in
      let args_locs, ptr_args_locs =
        List.fold_left add_arg_locs (nolocs, nolocs) args
      in
      assigned_locs, nolocs, args_locs, ptr_args_locs
    | Guard (exp, _, _) when Info.include_guards ->
      guarded_locs exp, nolocs, nolocs, nolocs
    | _ -> nolocs, nolocs, nolocs, nolocs

  let transfer ((_, e, _) as edge) (lw, pt) =
    let (assigned_locs, _, args_locs, _) as all_locs = compute_locs e pt in
    let written_locs = MemLoc.Set.union assigned_locs args_locs in
    let lw = LastWrites.transfer edge lw written_locs
    and pt = PtrTargets.transfer edge pt all_locs in
    Some (lw, pt)
end
